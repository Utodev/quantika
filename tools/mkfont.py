#!/usr/bin/env python3
"""mkfont.py: builds data/font.asm (the free character set, 256 x 8 bytes) from data/font_ascii.txt,
data/font_extra.txt, the accented letters (a letter and an accent) and the block graphics C0h-DFh.
Run from this project's folder: python3 tools/mkfont.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def read_glyphs(path):
    glyphs, code, rows = {}, None, []
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('#') and code is None or not line:
            continue
        if line.startswith('= '):
            code, rows = int(line[2:], 16), []
            continue
        rows.append(line.ljust(6, '.')[:6] + '..')
        if len(rows) == 8:
            glyphs[code] = rows
            code = None
    return glyphs


def to_byte(row):
    return sum(1 << (7 - i) for i, c in enumerate(row[:8]) if c == '#')


glyphs = read_glyphs(os.path.join(ROOT, 'data', 'font_ascii.txt'))
glyphs.update(read_glyphs(os.path.join(ROOT, 'data', 'font_extra.txt')))

# --- accented letters ---
DOTLESS_I = ['......', '......', '.##...', '..#...', '..#...', '..#...', '.###..', '......']
SMALL = {  # two-row accents over a small letter (rows 0-1)
    'acute': ['...#..', '..#...'], 'grave': ['.#....', '..#...'], 'circ': ['..#...', '.#.#..'],
    'uml': ['......', '.#.#..'], 'ring': ['.###..', '.#.#..'], 'tilde': ['.#..#.', '#.##..']}
CAPITAL = {  # one-row accents over a capital letter squeezed into rows 1-6
    'acute': '...##.', 'grave': '.##...', 'circ': '..#...', 'uml': '.#.#..', 'ring': '..#...',
    'tilde': '.#.#.#'}


def small(letter, accent):
    base = DOTLESS_I if letter == 'i' else glyphs[ord(letter)]
    return [r.ljust(8, '.') for r in SMALL[accent]] + base[2:]


def capital(letter, accent):
    base = glyphs[ord(letter)]
    squeezed = base[0:2] + base[3:7]           # drop row 2: six rows left
    return [CAPITAL[accent].ljust(8, '.')] + squeezed + ['........']


ACCENTED = {
    0x81: ('u', 'uml'), 0x82: ('e', 'acute'), 0x83: ('a', 'circ'), 0x84: ('a', 'uml'), 0x85: ('a', 'grave'),
    0x86: ('a', 'ring'), 0x88: ('e', 'circ'), 0x89: ('e', 'uml'), 0x8A: ('e', 'grave'), 0x8B: ('i', 'uml'),
    0x8C: ('i', 'circ'), 0x8D: ('i', 'grave'), 0x8E: ('A', 'uml'), 0x8F: ('A', 'ring'), 0x90: ('E', 'acute'),
    0x93: ('o', 'circ'), 0x94: ('o', 'uml'), 0x95: ('o', 'grave'), 0x96: ('u', 'circ'), 0x97: ('u', 'grave'),
    0x98: ('y', 'uml'), 0x99: ('O', 'uml'), 0x9A: ('U', 'uml'), 0xA0: ('a', 'acute'), 0xA1: ('i', 'acute'),
    0xA2: ('o', 'acute'), 0xA3: ('u', 'acute'), 0xA4: ('n', 'tilde'), 0xA5: ('N', 'tilde'), 0xB0: ('A', 'tilde'),
    0xB1: ('a', 'tilde'), 0xB2: ('I', 'tilde'), 0xB3: ('i', 'tilde'), 0xB4: ('O', 'tilde'), 0xB5: ('o', 'tilde'),
    0xB6: ('U', 'tilde'), 0xB7: ('u', 'tilde')}
for code, (letter, accent) in ACCENTED.items():
    glyphs[code] = capital(letter, accent) if letter.isupper() else small(letter, accent)

# --- block graphics: C0h-CFh the 16 quarter-block combinations, D0h-D7h rising bars,
#     D8h-DAh growing from the left; DBh-DFh are the standard's: full block, lower, left, right and upper
#     half (programs draw with them) ---
for n in range(16):
    top = ('###' if n & 1 else '...') + ('###' if n & 2 else '...')
    bottom = ('###' if n & 4 else '...') + ('###' if n & 8 else '...')
    glyphs[0xC0 + n] = [top + '..'] * 4 + [bottom + '..'] * 4
for n in range(8):
    glyphs[0xD0 + n] = ['........'] * (7 - n) + ['########'] * (n + 1)
    glyphs[0xD8 + n] = [('#' * (n + 1)).ljust(8, '.')] * 8
glyphs[0xDB] = ['########'] * 8
glyphs[0xDC] = ['........'] * 4 + ['########'] * 4
glyphs[0xDD] = ['####....'] * 8
glyphs[0xDE] = ['....####'] * 8
glyphs[0xDF] = ['########'] * 4 + ['........'] * 4

missing = [c for c in range(256) if c not in glyphs]
if missing:
    raise SystemExit('no glyph for ' + ' '.join('%02X' % c for c in missing))

out = ['; font.asm: the free character set, 256 characters x 8 bytes (bit 7 = left pixel).',
       '; Generated by tools/mkfont.py from data/font_ascii.txt and data/font_extra.txt: edit those.',
       'FontData:']
for c in range(256):
    shown = chr(c) if 0x20 < c < 0x7F else ''
    out.append('        db ' + ','.join('$%02X' % to_byte(r) for r in glyphs[c]) + '   ; %02Xh %s' % (c, shown))
open(os.path.join(ROOT, 'data', 'font.asm'), 'w').write('\n'.join(out) + '\n')
print('data/font.asm: 256 glyphs')
