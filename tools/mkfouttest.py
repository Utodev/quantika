#!/usr/bin/env python3
"""mkfouttest.py: writes tests/foutcases.inc for tests/fout.asm: numbers (VALTYP and DAC) for FOUT,
whose text the test keeps (16 bytes a case). Run from this project's folder: python3 tools/mkfouttest.py"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bcdlib import bcd, integer
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

I, S, D = 2, 4, 8
CASES = [(I, 0), (I, 5), (I, -5), (I, 32767), (I, -32768), (I, 1000),
         (S, '1.5'), (S, '-1.5'), (S, '0.5'), (S, '0.25'), (S, '0.01'), (S, '0.001'), (S, '0.0001'),
         (S, '0.00001'), (S, '123456'), (S, '999999'), (S, '1000000'), (S, '1E7'), (S, '12345.6'),
         (S, '1E14'), (S, '1E15'), (S, '1E16'), (S, '1E62'), (S, '1.23456E-10'), (S, '100'), (S, '3.14159'),
         (S, '0.1'), (S, '-0.00012'), (S, '0'), (S, '1E-64'), (S, '7E-63'), (S, '0.0123'),
         (D, '3.1415926535898'), (D, '1E14'), (D, '99999999999999'), (D, '1E15'), (D, '1E16'),
         (D, '0.0000001'), (D, '0.01'), (D, '0.001'), (D, '123456789.123'), (D, '-2.5'), (D, '0.1'),
         (D, '12345678901234'), (D, '1.2345678901234E-5'), (D, '1E-10'), (D, '100'), (D, '0')]
lines = ['; foutcases.inc: generated by tools/mkfouttest.py', 'Cases:']
for t, v in CASES:
    b = integer(v) if t == I else bcd(v, 6 if t == S else 14)
    lines.append('        db %d : db %s' % (t, ','.join('$%02X' % x for x in b)))
lines.append('        db 0')
open(os.path.join(ROOT, 'tests', 'foutcases.inc'), 'w').write('\n'.join(lines) + '\n')
print(len(CASES), 'cases')
