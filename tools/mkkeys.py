#!/usr/bin/env python3
"""mkkeys.py: builds data/keymap.asm, the key tables of the free BIOS (international keyboard).
Rows 0-5 of the matrix are the character keys (48 keys, row * 8 + bit); each table gives the code of
each key in one state of the modifiers: 0 = no code. The GRAPH and CODE layers are this ROM's own.
Run from this project's folder: python3 tools/mkkeys.py"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEAD = None   # the dead (accent) key gives no code by itself

def letters(base):
    return [base + i for i in range(26)]

KEYS = list('01234567' '89-=\\[];' "'`,./") + [DEAD] + list('abcdefghijklmnopqrstuvwxyz')
SHIFTED = list(')!@#$%^&' '*(_+|{}:' '"~<>?') + [DEAD] + list('ABCDEFGHIJKLMNOPQRSTUVWXYZ')
assert len(KEYS) == 48 and len(SHIFTED) == 48

# GRAPH: digits and punctuation give the graphic characters 01h-1Fh (sent as 01h, code + 40h), letters
# the block characters C0h-D9h; with SHIFT, the box lines and the Greek and maths signs E0h-F9h
GRAPH = [0x0A, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
         0x08, 0x09, 0x16, 0x1E, 0x15, 0x17, 0x18, 0x0F,
         0x19, 0x1A, 0x1C, 0x1D, 0x1B, 0] + letters(0xC0)
GRAPH_SHIFT = [0x1F, 0x0B, 0x0C, 0x0D, 0x0E, 0x10, 0x11, 0x12,
               0x13, 0x14, 0xDA, 0xDB, 0xDC, 0xDD, 0xDE, 0xDF,
               0xFA, 0xFB, 0xFE, 0xFF, 0x7F, 0] + letters(0xE0)
# CODE: accented letters and symbols of the international set
CODE = [0xF8, 0xAD, 0xFD, 0x9C, 0x9B, 0x9D, 0x9F, 0xBF,
        0xBE, 0xBD, 0xF6, 0xF7, 0xF0, 0xAE, 0xAF, 0xF9,
        0xA6, 0xA7, 0xF3, 0xF2, 0xAB, 0]
CODE += [{'a': 0xA0, 'b': 0xE1, 'c': 0x87, 'd': 0xEB, 'e': 0x82, 'f': 0xED, 'g': 0xE2, 'h': 0x85,
          'i': 0xA1, 'j': 0x8D, 'k': 0x8A, 'l': 0x95, 'm': 0xE6, 'n': 0xA4, 'o': 0xA2, 'p': 0xE3,
          'q': 0x83, 'r': 0x88, 's': 0xE5, 't': 0xE7, 'u': 0xA3, 'v': 0x93, 'w': 0x96, 'x': 0x91,
          'y': 0x98, 'z': 0x84}[c] for c in 'abcdefghijklmnopqrstuvwxyz']
CODE_SHIFT = [0xFC, 0xA8, 0xBA, 0xAC, 0xF1, 0xEC, 0xFB, 0xBC,
              0xB8, 0xB9, 0xA9, 0xAA, 0xF4, 0xF5, 0xEF, 0xEE,
              0x9E, 0xBB, 0x86, 0x8C, 0x97, 0]
CODE_SHIFT += [{'a': 0x8F, 'b': 0xB1, 'c': 0x80, 'd': 0xB3, 'e': 0x90, 'f': 0xB5, 'g': 0xB7, 'h': 0x89,
                'i': 0xB2, 'j': 0x8B, 'k': 0x94, 'l': 0x81, 'm': 0xEA, 'n': 0xA5, 'o': 0xB4, 'p': 0xE8,
                'q': 0x8E, 'r': 0x99, 's': 0xE4, 't': 0xE9, 'u': 0xB6, 'v': 0x9A, 'w': 0xB0, 'x': 0x92,
                'y': 0xB9, 'z': 0xEC}[c] for c in 'abcdefghijklmnopqrstuvwxyz']
for t in (GRAPH, GRAPH_SHIFT, CODE, CODE_SHIFT):
    assert len(t) == 48, len(t)

# Rows 6-10: 1-5 are the function keys F1-F5 (F6-F10 with SHIFT), 0 no code (modifiers, STOP)
SPECIAL = [0, 0, 0, 0, 0, 1, 2, 3,                         # SHIFT CTRL GRAPH CAPS CODE F1 F2 F3
           4, 5, 0x1B, 0x09, 0, 0x08, 0x18, 0x0D,          # F4 F5 ESC TAB STOP BS SELECT RETURN
           0x20, 0x0B, 0x12, 0x7F, 0x1D, 0x1E, 0x1F, 0x1C, # SPACE HOME INS DEL LEFT UP DOWN RIGHT
           ord('*'), ord('+'), ord('/'), ord('0'), ord('1'), ord('2'), ord('3'), ord('4'),
           ord('5'), ord('6'), ord('7'), ord('8'), ord('9'), ord('-'), ord(','), ord('.')]

def code(k):
    return 0 if k is None else (ord(k) if isinstance(k, str) else k)

def table(name, comment, values):
    out = ['; ' + comment, name + ':']
    for r in range(0, len(values), 8):
        out.append('        db ' + ','.join('$%02X' % code(v) for v in values[r:r + 8]))
    return out

out = ['; keymap.asm: key code tables. Generated by tools/mkkeys.py: edit that file.', '']
out += table('KeysNormal', 'rows 0-5, no modifier', KEYS) + ['']
out += table('KeysShift', 'rows 0-5 with SHIFT', SHIFTED) + ['']
out += table('KeysGraph', 'rows 0-5 with GRAPH', GRAPH) + ['']
out += table('KeysGraphShift', 'rows 0-5 with GRAPH and SHIFT', GRAPH_SHIFT) + ['']
out += table('KeysCode', 'rows 0-5 with CODE', CODE) + ['']
out += table('KeysCodeShift', 'rows 0-5 with CODE and SHIFT', CODE_SHIFT) + ['']
out += table('KeysSpecial', 'rows 6-10 (any modifier): 1-5 = function key, 0 = none', SPECIAL)
open(os.path.join(ROOT, 'data', 'keymap.asm'), 'w').write('\n'.join(out) + '\n')
print('data/keymap.asm')
