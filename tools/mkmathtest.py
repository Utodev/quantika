#!/usr/bin/env python3
"""mkmathtest.py: writes tests/mathcases.inc, the cases of tests/math.asm: each case calls a Math-Pack
entry with VALTYP, DAC and ARG set, and the test keeps VALTYP and the 8 bytes of DAC after it.
Numbers are written as text here and encoded as the BCD format of the Math-Pack (or integers).
Run from this project's folder: python3 tools/mkmathtest.py"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bcdlib import bcd, integer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

D, S, I = 8, 4, 2
CASES = [
    # entry, type, DAC, ARG
    ('DECADD', D, '1.5', '2.25'), ('DECADD', D, '0.1', '0.2'), ('DECADD', D, '5', '-7'),
    ('DECADD', D, '-3', '3'), ('DECADD', D, '99999999999999', '1'), ('DECADD', D, '0.1', '0.000000000000005'),
    ('DECADD', D, '0.1', '0.000000000000004'), ('DECADD', D, '1E20', '1'), ('DECADD', D, '123.456', '-0.000456'),
    ('DECSUB', D, '1', '0.99999999999999'), ('DECSUB', D, '10', '10'), ('DECSUB', D, '-2.5', '1.25'),
    ('DECMUL', D, '7', '6'), ('DECMUL', D, '0.5', '0.5'), ('DECMUL', D, '-12.5', '8'),
    ('DECMUL', D, '33333333333333', '3'), ('DECMUL', D, '1.0000001', '1.0000001'), ('DECMUL', D, '0', '5'),
    ('DECDIV', D, '1', '3'), ('DECDIV', D, '2', '3'), ('DECDIV', D, '10', '4'), ('DECDIV', D, '-9', '3'),
    ('DECDIV', D, '1', '7'), ('DECDIV', D, '123456789', '0.001'),
]
CONVERSIONS = [
    ('FRCINT', D, '2.5'), ('FRCINT', D, '-2.5'), ('FRCINT', D, '3.49'), ('FRCINT', D, '32767.4'),
    ('FRCINT', D, '-32768.4'), ('FRCINT', D, '0.5'), ('FRCINT', D, '0.4'), ('FRCINT', D, '-0.6'),
    ('FRCSNG', D, '1.23456789'), ('FRCSNG', D, '9.9999996'), ('FRCSNG', D, '-0.0001234565'),
    ('FRCDBL', I, 12345), ('FRCDBL', I, -32768), ('FRCDBL', I, 0), ('FRCSNG', I, 100),
    ('FIXER', D, '-2.7'), ('FIXER', D, '12345.678'), ('FIXER', D, '0.9'),
    ('NEG', D, '1.5'), ('NEG', I, 300), ('ABSFN', D, '-4'), ('SGN', D, '-0.001'), ('SGN', I, 0),
]

lines = ['; mathcases.inc: generated by tools/mkmathtest.py', 'Cases:']
for entry, t, dac, arg in CASES:
    lines.append('        dw %s : db %d : db %s : db %s' % (entry, t, ','.join('$%02X' % b for b in bcd(dac)),
                                                         ','.join('$%02X' % b for b in bcd(arg))))
for entry, t, dac in CONVERSIONS:
    v = integer(dac) if t == I else bcd(dac)
    lines.append('        dw %s : db %d : db %s : ds 8' % (entry, t, ','.join('$%02X' % b for b in v)))
lines.append('        dw 0')
open(os.path.join(ROOT, 'tests', 'mathcases.inc'), 'w').write('\n'.join(lines) + '\n')
print(len(CASES) + len(CONVERSIONS), 'cases')
