#!/usr/bin/env python3
"""mktokens.py: builds data/keywords.asm, the keywords of FBASIC with the token numbers of the original BASIC
(fixed: programs are saved with them), and common/tokens.inc with a name for each token.

The tokenizer looks a word up in the standard's keyword table (basic/kwtable.asm, at its fixed
address). LIST finds a token's name in StatementNames (tokens 81h-FCh) or
FunctionNames (FFh 81h-B0h): the names one after another, the last letter of each with bit 7 set.
Run from this project's folder: python3 tools/mktokens.py"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

STATEMENTS = """END FOR NEXT DATA INPUT DIM READ LET GOTO RUN IF RESTORE GOSUB RETURN REM STOP PRINT CLEAR LIST
NEW ON WAIT DEF POKE CONT CSAVE CLOAD OUT LPRINT LLIST CLS WIDTH ELSE TRON TROFF SWAP ERASE ERROR RESUME
DELETE AUTO RENUM DEFSTR DEFINT DEFSNG DEFDBL LINE OPEN FIELD GET PUT CLOSE LOAD MERGE FILES LSET RSET
SAVE LFILES CIRCLE COLOR DRAW PAINT BEEP PLAY PSET PRESET SOUND SCREEN VPOKE SPRITE VDP BASE CALL TIME
KEY MAX MOTOR BLOAD BSAVE DSKO$ SET NAME KILL IPL COPY CMD LOCATE TO THEN TAB( STEP USR FN SPC( NOT ERL
ERR STRING$ USING INSTR ' VARPTR CSRLIN ATTR$ DSKI$ OFF INKEY$ POINT > = < + - * / ^ AND OR XOR EQV IMP
MOD \\""".split()
FUNCTIONS = """LEFT$ RIGHT$ MID$ SGN INT ABS SQR RND SIN LOG EXP COS TAN ATN FRE INP POS LEN STR$ VAL ASC CHR$
PEEK VPEEK SPACE$ OCT$ HEX$ LPOS BIN$ CINT CSNG CDBL FIX STICK STRIG PDL PAD DSKF FPOS CVI CVS CVD EOF LOC
LOF MKI$ MKS$ MKD$""".split()
assert len(STATEMENTS) == 0xFC - 0x80, len(STATEMENTS)
assert len(FUNCTIONS) == 0xB0 - 0x80, len(FUNCTIONS)

def symbol(word):
    return (word.replace('$', 'Str').replace('(', 'Paren').replace("'", 'Apostrophe')
            .replace('>', 'Greater').replace('=', 'Equal').replace('<', 'Less').replace('+', 'Plus')
            .replace('-', 'Minus').replace('*', 'Times').replace('/', 'Slash').replace('^', 'Power')
            .replace('\\', 'Backslash'))

def pretty(word):
    name = symbol(word.lower())
    return name[0].upper() + name[1:]

out = ['; keywords.asm: generated by tools/mktokens.py (see there for the format)', '']
inc = ['; tokens.inc: generated by tools/mktokens.py: the token numbers of the original BASIC', '']
words = []
for i, w in enumerate(STATEMENTS):
    inc.append('Tk%-12s equ $%02X' % (pretty(w), 0x81 + i))
    if w[0].isalpha():
        words.append((w, 0x81 + i, False))
for i, w in enumerate(FUNCTIONS):
    inc.append('Fn%-12s equ $%02X       ; after FFh' % (pretty(w), 0x81 + i))
    words.append((w, 0x81 + i, True))
inc.append('TkFunction     equ $FF       ; the prefix of the function tokens')

def names(label, lst):
    res = [label + ':']
    for w in lst:
        b = [ord(c) for c in w]
        b[-1] |= 0x80
        res.append('        db ' + ','.join('$%02X' % x for x in b) + '   ; ' + w)
    return res
out += [''] + names('StatementNames', STATEMENTS) + [''] + names('FunctionNames', FUNCTIONS)
open(os.path.join(ROOT, 'data', 'keywords.asm'), 'w').write('\n'.join(out) + '\n')
open(os.path.join(ROOT, 'common', 'tokens.inc'), 'w').write('\n'.join(inc) + '\n')
print('keywords:', len(words))
