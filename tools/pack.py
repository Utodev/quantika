#!/usr/bin/env python3
"""pack.py: places the movable modules of a ROM in its free areas.

    pack.py measure <layout.txt> <out.inc>
        writes an include that puts every module one after another from 8000h (outside the ROM), with
        labels at their ends, so one assembly gives their sizes
    pack.py place <layout.txt> <symbols.sym> <out.inc>
        reads the sizes from the symbols of that assembly and the free areas, puts each module in an
        area (largest modules first, each in the smallest area it fits) and writes the final include

layout.txt: lines 'area <start> <end>' (hex, or a symbol of the measuring assembly, end excluded),
'gaps <mathpack.inc> <from> <to>' (the space between the fixed entries of that file in that range),
'module <file> page0|any' (page0: it must be in 0000h-3FFFh). '#' starts a comment."""
import re
import sys


def parse_layout(path):
    areas, modules = [], []
    for line in open(path):
        line = line.split('#')[0].split()
        if not line:
            continue
        if line[0] == 'area':
            areas.append(('area', line[1], line[2]))
        elif line[0] == 'gaps':
            areas.append(('gaps', line[1], int(line[2], 16), int(line[3], 16)))
        elif line[0] == 'module':
            modules.append((line[1], line[2]))
    return areas, modules


def label(path):
    return 'Module_' + re.sub(r'\W', '_', path)


def entry_gaps(inc, lo, hi):
    """free space between the 'equ' entries of an include, which hold 3 bytes each (a JP) or 1 byte when
    the next entry is the byte after"""
    addrs = sorted(int(m.group(1), 16) for m in
                   (re.match(r'\w+\s+equ \$([0-9A-F]{4})', l) for l in open(inc)) if m)
    addrs = [a for a in addrs if lo <= a < hi]
    out = []
    for i, a in enumerate(addrs):
        nxt = addrs[i + 1] if i + 1 < len(addrs) else hi
        end = min(a + 3, nxt)
        if nxt > end:
            out.append((end, nxt))
    return out


def measure(layout, out):
    _, modules = parse_layout(layout)
    lines = ['; generated by tools/pack.py: every module in a row, to measure them', '        org $8000']
    for path, _ in modules:
        lines += ['%s_Start:' % label(path), '        include "%s"' % path, '%s_End:' % label(path)]
    open(out, 'w').write('\n'.join(lines) + '\n')


def place(layout, symfile, out):
    areas, modules = parse_layout(layout)
    syms = {}
    for line in open(symfile):
        m = re.match(r'(\S+): EQU 0x([0-9A-F]+)', line)
        if m:
            syms[m.group(1)] = int(m.group(2), 16)

    def value(v):
        return syms[v] if v in syms else int(v, 16)

    free = []
    for a in areas:
        if a[0] == 'area':
            free.append([value(a[1]), value(a[2])])
        else:
            free += [list(g) for g in entry_gaps(a[1], a[2], a[3])]
    sizes = [(syms[label(p) + '_End'] - syms[label(p) + '_Start'], p, c) for p, c in modules]
    placed = []
    # page 0 modules first (they have fewer places), each group the largest first
    for size, path, constraint in sorted(sizes, key=lambda m: (m[2] != 'page0', -m[0])):
        fits = [f for f in free if f[1] - f[0] >= size and (constraint == 'any' or f[0] + size <= 0x4000)]
        if not fits:
            sys.exit('pack.py: no room for %s (%d bytes); free areas: %s' % (
                path, size, ', '.join('%04X+%d' % (f[0], f[1] - f[0]) for f in free)))
        best = min(fits, key=lambda f: f[1] - f[0])
        placed.append((best[0], path, size))
        best[0] += size
    lines = ['; generated by tools/pack.py: where each module goes']
    for addr, path, size in sorted(placed):
        lines += ['        org $%04X                     ; %d bytes' % (addr, size),
                  '%s_Start:' % label(path), '        include "%s"' % path, '%s_End:' % label(path)]
    open(out, 'w').write('\n'.join(lines) + '\n')
    left = sum(f[1] - f[0] for f in free)
    print('pack.py: %d modules placed, %d bytes free in %d areas (largest %d)' % (
        len(placed), left, len(free), max(f[1] - f[0] for f in free)))


if __name__ == '__main__':
    if sys.argv[1] == 'measure':
        measure(sys.argv[2], sys.argv[3])
    else:
        place(sys.argv[2], sys.argv[3], sys.argv[4])
